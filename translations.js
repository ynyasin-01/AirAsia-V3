/**
 * Global active language tracking
 */
window.AIRASIA_CURRENT_LANG = 'EN';

/**
 * Global helper: window.t(key, fallback, params)
 * Resolves a translation string for the active language with optional parameter interpolation.
 */
window.t = function(key, fallback = '', params = null) {
  const lang = window.AIRASIA_CURRENT_LANG || (window.State && window.State.selectedLanguage) || (function() {
    try { return localStorage.getItem('airasia_selected_language'); } catch(e) { return null; }
  })() || 'EN';

  const dict = (window.AIRASIA_TRANSLATIONS && window.AIRASIA_TRANSLATIONS[lang]) || {};
  const enDict = (window.AIRASIA_TRANSLATIONS && window.AIRASIA_TRANSLATIONS['EN']) || {};

  let text = dict[key] !== undefined ? dict[key] : (enDict[key] !== undefined ? enDict[key] : fallback);
  if (text === undefined || text === null) text = fallback || key;

  if (params && typeof params === 'object') {
    Object.keys(params).forEach(pKey => {
      text = text.replace(new RegExp('\\{' + pKey + '\\}', 'g'), params[pKey]);
    });
  }
  return text;
};

/**
 * Global DOM Translation Applier: window.applyLanguageTranslations(code)
 * Applies i18n dictionaries to all data-i18n, data-i18n-placeholder, data-i18n-title,
 * data-i18n-aria-label, data-i18n-html elements across the entire page.
 */
window.applyLanguageTranslations = function(code) {
  const targetLang = code || window.AIRASIA_CURRENT_LANG || (window.State && window.State.selectedLanguage) || (function() {
    try { return localStorage.getItem('airasia_selected_language'); } catch(e) { return null; }
  })() || 'EN';

  window.AIRASIA_CURRENT_LANG = targetLang;
  if (window.State) {
    window.State.selectedLanguage = targetLang;
  }

  const dict = (window.AIRASIA_TRANSLATIONS && window.AIRASIA_TRANSLATIONS[targetLang]) || {};
  const fallbackDict = (window.AIRASIA_TRANSLATIONS && window.AIRASIA_TRANSLATIONS['EN']) || {};

  function resolveKey(key) {
    if (!key) return null;
    if (dict[key] !== undefined) return dict[key];
    if (fallbackDict[key] !== undefined) return fallbackDict[key];
    return null;
  }

  // 1. Text elements: data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = resolveKey(key);
    if (val !== null) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.value = val;
      } else if (val.includes('<') && val.includes('>')) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    }
  });

  // 2. Placeholders: data-i18n-placeholder and data-i18n-ph
  document.querySelectorAll('[data-i18n-placeholder], [data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder') || el.getAttribute('data-i18n-ph');
    const val = resolveKey(key);
    if (val !== null) {
      el.placeholder = val;
    }
  });

  // 3. Tooltips / Titles: data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const val = resolveKey(key);
    if (val !== null) {
      el.title = val;
    }
  });

  // 4. ARIA labels: data-i18n-aria-label
  document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria-label');
    const val = resolveKey(key);
    if (val !== null) {
      el.setAttribute('aria-label', val);
    }
  });

  // 5. HTML Content: data-i18n-html
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    const val = resolveKey(key);
    if (val !== null) {
      el.innerHTML = val;
    }
  });

  // 6. Update document lang attribute
  if (document.documentElement) {
    document.documentElement.lang = targetLang.toLowerCase();
  }
};
